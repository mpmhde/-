#Алгоритм сортировки вставками
def insertion_sort(arr):
    # Перебираем элементы массива, начиная со второго (индекс 1)
    for i in range(1, len(arr)):  
        key = arr[i]              # Берём текущий элемент для вставки
        j = i - 1                 # Переменная для перебора предыдущих элементов
        
        # Перемещаемся назад, пока находим больший элемент впереди
        while j >= 0 and key < arr[j]:      
            arr[j + 1] = arr[j]  # Смещаем большие элементы вправо
            j -= 1               # Переход к следующему левому элементу
            
        # Вставляем текущий элемент в правильную позицию
        arr[j + 1] = key         
    
    return arr                   # Возвращаем отсортированный массив


# Пример использования:
