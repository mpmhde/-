#Пирамидальная сортировка (Heap Sort)
def heapify(arr, n, i):
    """
    Приводит поддерево с корнем в индексе 'i' к состоянию кучи.
    Параметры:
    arr - исходный массив
    n - размер дерева (массива)
    i - индекс корня текущего поддерева
    """
    largest = i                            # Сначала считаем корень максимальным
    left_child = 2 * i + 1                 # Рассчитываем индекс левого потомка
    right_child = 2 * i + 2                # Рассчитываем индекс правого потомка
    
    # Если левый потомок существует и больше родителя
    if left_child < n and arr[left_child] > arr[largest]:
        largest = left_child
    
    # То же самое для правого потомка
    if right_child < n and arr[right_child] > arr[largest]:
        largest = right_child
    
    # Если максимальное значение оказалось не в корне, меняем местами
    if largest != i:
        arr[i], arr[largest] = arr[largest], arr[i]  # Меняем элементы местами
        heapify(arr, n, largest)                     # Рецурсивно приводим новую вершину к виду кучи


def heapsort(arr):
    """
    Выполняет сортировку массива методом пирамидальной сортировки.
    """
    n = len(arr)
    
    # Строим кучу (преобразовываем массив в max-кучу)
    for i in range(n//2 - 1, -1, -1):
        heapify(arr, n, i)
    
    # Один за другим извлекаем элементы из кучи
    for i in range(n-1, 0, -1):
        arr[i], arr[0] = arr[0], arr[i]  # Меняем последний элемент с корневым
        heapify(arr, i, 0)                # Восстанавливаем структуру кучи
    
    return arr                             # Возвращаем отсортированный массив


# Пример использования:
