#Алгоритм сортировки Шелла
def shell_sort(arr):
    n = len(arr)                     # Определяем длину массива
    gap = n // 2                     # Изначально задаём начальное расстояние ("gap") равное половине размера массива
    
    # Продолжаем цикл, пока размер интервала (gap) больше нуля
    while gap > 0:
        # Для каждого фиксированного расстояния проходим по массиву и выполняем частичную сортировку вставками
        for i in range(gap, n):
            temp = arr[i]            # Запоминаем текущий элемент
            j = i                    # Используем второй индекс для перемещения элемента на нужную позицию
            
            # Сдвигаем элементы вправо, пока встречается элемент, больший текущего
            while j >= gap and arr[j-gap] > temp:
                arr[j] = arr[j-gap] # Передвигаем элемент на одну позицию вправо
                j -= gap             # Сокращаем индекс на величину интервала
            
            # Вставляем элемент на соответствующую позицию
            arr[j] = temp
        
        # Уменьшаем интервал ("gap"), переходя к следующей фазе сортировки
        gap //= 2                    # Каждое следующее разделение уменьшает дистанцию вдвое
    
    return arr                      # Возвращаем отсортированный массив


# Пример использования:
