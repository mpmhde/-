#Последовательный поиск (линейный поиск)
def sequential_search(arr, target):
    """
    Последовательный поиск заданного элемента в массиве.
    Возвращает индекс элемента, если он найден, иначе None.
    """
    # Просматриваем каждый элемент массива
    for index, value in enumerate(arr):
        # Если нашли нужный элемент, возвращаем его индекс
        if value == target:
            return index
    
    # Если элемент не найден, возвращаем None
    return None


