#Быстрая сортировка (Quicksort)
def quick_sort(arr):
    """
    Быстрая сортировка QuickSort
    :param arr: Исходный массив
    :return: Отсортированный массив
    """
    if len(arr) <= 1:
        return arr  # Массив длиной 0 или 1 уже отсортирован
    
    pivot = arr[len(arr) // 2]  # Выбор центрального элемента в качестве опорного
    
    # Формируем три списка: элементы меньше опорного, равные и больше опорного
    left = [x for x in arr if x < pivot]
    middle = [x for x in arr if x == pivot]
    right = [x for x in arr if x > pivot]
    
    # Рекурсивно применяем сортировку к левым и правым частям
    return quick_sort(left) + middle + quick_sort(right)


# Пример использования:
if __name__ == "__main__":
    example_list = [10, 7, 8, 9, 1, 5]
    sorted_list = quick_sort(example_list)
    print("Отсортированный список:", sorted_list)

