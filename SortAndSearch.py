#Интерполирующий поиск (Interpolation Search)
def interpolation_search(arr, target):
    """
    Реализует интерполирующий поиск в отсортированном массиве.
    Возвращает индекс элемента, если он найден, иначе -1.
    """
    low = 0                               # Нижняя граница поиска
    high = len(arr) - 1                   # Верхняя граница поиска
    
    # Продолжаем поиск, пока нижний индекс меньше верхнего
    while low <= high and target >= arr[low] and target <= arr[high]:
        # Вычисляем приближённую позицию искомого элемента
        pos = low + ((target - arr[low]) * (high - low)) // (arr[high] - arr[low])
        
        # Проверяем найденный элемент
        if arr[pos] == target:
            return pos                    # Вернуть индекс, если элемент найден
        elif arr[pos] < target:
            low = pos + 1                 # Пересчитываем нижнюю границу
        else:
            high = pos - 1                # Пересчитываем верхнюю границу
    
    # Если элемент не найден, вернуть -1
    return -1


