#Алгоритм сортировки слиянием (Merge Sort)
def merge_sort(arr):
    """
    Реализация сортировки слиянием.
    :param arr: Входной массив
    :return: Отсортированный массив
    """
    # Базовый случай: если длина массива равна 1 или меньше, возвращаем массив (так как он уже отсортирован)
    if len(arr) <= 1:
        return arr
    
    # Определяем середину массива
    mid = len(arr) // 2
    
    # Рекурсивно сортируем левую половину массива
    left_half = merge_sort(arr[:mid])
    
    # Рекурсивно сортируем правую половину массива
    right_half = merge_sort(arr[mid:])
    
    # Объединяем отсортированные половины
    return merge(left_half, right_half)


def merge(left, right):
    """
    Вспомогательная функция для объединения двух отсортированных массивов.
    :param left: Левый отсортированный массив
    :param right: Правый отсортированный массив
    :return: Объединённый отсортированный массив
    """
    result = []           # Результирующий массив
    i = j = 0             # Индексы для левого и правого массивов соответственно
    
    # Пока оба массива содержат элементы, выбираем наименьший и добавляем в результирующий массив
    while i < len(left) and j < len(right):
        if left[i] < right[j]:
            result.append(left[i])  # Добавляем элемент из левой части
            i += 1                  # Переходим к следующему элементу в левом массиве
        else:
            result.append(right[j]) # Добавляем элемент из правой части
            j += 1                  # Переходим к следующему элементу в правом массиве
    
    # Добавляем оставшиеся элементы из левой части (если остались)
    while i < len(left):
        result.append(left[i])
        i += 1
    
    # Добавляем оставшиеся элементы из правой части (если остались)
    while j < len(right):
        result.append(right[j])
        j += 1
    
    return result

