#Бинарный поиск (Binary Search)
def binary_search(arr, target):
    """
    Бинарный поиск заданного элемента в отсортированном массиве.
    Возвращает индекс элемента, если он найден, иначе -1.
    """
    low = 0                         # Нижняя граница поиска
    high = len(arr) - 1             # Верхняя граница поиска
    
    # Продолжаем искать, пока границы не пересекутся
    while low <= high:
        mid = (low + high) // 2     # Средний индекс массива
        
        # Проверяем средний элемент
        if arr[mid] == target:
            return mid              # Нашли элемент, возвращаем его индекс
        elif arr[mid] < target:
            low = mid + 1           # Если цель больше среднего, сужаем диапазон снизу
        else:
            high = mid - 1          # Если цель меньше среднего, сужаем диапазон сверху
    
    # Если элемент не найден, возвращаем -1
    return -1


