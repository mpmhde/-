#Алгоритм сортировки обменом
def bubble_sort(arr):
    n = len(arr)      # Получаем длину массива
    
    # Основной цикл проходит по всему списку, уменьшая количество итераций на каждом этапе
    for i in range(n):     
        swapped = False     # Флаг для отслеживания наличия изменений в текущем проходе
        
        # Внутренний цикл сравнивает соседние элементы и меняет их местами, если порядок неверный
        for j in range(0, n-i-1):       
            if arr[j] > arr[j+1]:       # Проверяем условие: если предыдущий элемент больше последующего
                arr[j], arr[j+1] = arr[j+1], arr[j]  # Обмениваем элементы местами
                swapped = True          # Устанавливаем флаг, показывающий, что была произведена замена
                
        # Если ни одной замены не произошло в последнем проходе, значит массив уже отсортирован
        if not swapped:                 
            break                       # Выходим досрочно из основного цикла
            
    return arr                          # Возвращаем отсортированный массив


