#Фибоначчиевый поиск (Fibonacci Search)
def fibonacci_search(arr, target):
    """
    Реализует фибоначчий поиск в отсортированном массиве.
    Возвращает индекс элемента, если он найден, иначе -1.
    """
    size = len(arr)                                  # Длина массива
    
    # Генератор первых k чисел Фибоначчи
    def generate_fib_sequence(k):
        a, b = 0, 1
        sequence = []
        for _ in range(k):
            sequence.append(a)
            a, b = b, a+b
        return sequence
    
    # Генерируем последовательность Фибоначчи достаточной длины
    fib_seq = generate_fib_sequence(size + 1)
    
    offset = -1                                      # Текущий смещение
    idx = 0                                          # Индекс в последовательности Фибоначчи
    
    # Ищем наибольшее число Фибоначчи меньше или равное длине массива
    while fib_seq[idx] < size:
        idx += 1
    
    # Остаточная длина для последнего сравнения
    remaining_length = fib_seq[idx-1]
    
    # Основная часть поиска
    while remaining_length > 0:
        # Проверяем текущую позицию
        check_pos = min(offset + fib_seq[idx-2], size - 1)
        
        # Сравниваем текущий элемент с искомым
        if arr[check_pos] == target:
            return check_pos                        # Значение найдено
        elif arr[check_pos] < target:
            # Цель больше текущего элемента, идём дальше
            offset = check_pos
            idx -= 1                                # Переходим к следующему числу Фибоначчи
        else:
            # Цель меньше текущего элемента, отступаем назад
            idx -= 2                                # Пропускаем два числа Фибоначчи
        
        # Обновляем остаточную длину
        remaining_length = fib_seq[idx-1]
    
    # Если элемент не найден, возвращаем -1
    return -1


